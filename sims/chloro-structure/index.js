// ——— геометрия: всё задано числами здесь, чтобы рисунок и подписи брались из одного источника ———
const RO = [2.05, 0.94, 1.14], RI = [1.90, 0.79, 0.99];                     // полуоси наружной и внутренней мембран
const GRANA = [[-1.22, 0.00, -0.12, 3], [-0.82, 0.03, 0.26, 4], [-0.42, -0.03, -0.30, 3], [-0.02, 0.03, 0.14, 5], [0.38, -0.02, -0.30, 4], [0.76, 0.03, 0.22, 3], [1.08, 0.00, -0.14, 3]];
const STEP = 0.064;                                                           // расстояние между тилакоидами в гране
const LAM = [];                                                               // ламеллы: по две между соседними гранами
GRANA.slice(0, -1).forEach((a, i) => { const b = GRANA[i + 1]; for (const lvl of [-1, 1]) LAM.push([a, b, lvl * STEP * (1 + (i % 2))]); });
const STARCH = [1.56, -0.02, -0.08], DNA = [-1.60, 0.02, 0.0];
const RIBO = [[-1.38, 0.10, 0.18], [-1.44, 0.07, 0.13], [-1.33, 0.06, 0.12]];
const f = n => n.toFixed(4);
const v3 = a => `vec3(${a.map(f).join(',')})`;

const glsl = `
const float hazeMaterial = 3.0;
const vec3 RO = ${v3(RO)}, RI = ${v3(RI)};
float cutPlane(vec3 p) { return p.z - 0.30 + 0.38 * p.y; }       // всё, что перед этой плоскостью, у мембран срезано

float grana(vec3 p) {
  float d = 1e3;
  ${GRANA.map(([x, y, z, k]) => `{ vec3 q = p - ${v3([x, y, z])}; q.y -= ${f(STEP)} * clamp(round(q.y / ${f(STEP)}), -${k}.0, ${k}.0); d = min(d, sdDisc(q, 0.205, 0.013, 0.012)); }`).join('\n  ')}
  return d;
}
float lamellae(vec3 p) {
  float d = 1e3;
  ${LAM.map(([a, b, y]) => { const dx = b[0] - a[0], dz = b[2] - a[2], len = Math.hypot(dx, dz), c = dx / len, s = dz / len;
    return `{ vec3 q = p - ${v3([(a[0] + b[0]) / 2, (a[1] + b[1]) / 2 + y, (a[2] + b[2]) / 2])}; q.xz = vec2(${f(c)} * q.x + ${f(s)} * q.z, ${f(-s)} * q.x + ${f(c)} * q.z); d = min(d, sdBox(q, vec3(${f(len / 2)}, 0.004, 0.075), 0.011)); }`; }).join('\n  ')}
  return d;
}
vec2 map(vec3 p) {
  float cut = cutPlane(p);
  vec2 r = vec2(max(abs(sdEll(p, RO)) - 0.03, cut), 1.0);
  r = U(r, vec2(max(abs(sdEll(p, RI)) - 0.024, cut), 2.0));
  r = U(r, vec2(grana(p), 4.0));
  r = U(r, vec2(lamellae(p), 5.0));
  vec3 q = p - ${v3(DNA)}; q.xy = mat2(0.8, -0.6, 0.6, 0.8) * q.xy; q.y += 0.018 * sin(atan(q.z, q.x) * 3.0 + uTime);
  r = U(r, vec2(sdTorus(q, vec2(0.13, 0.013)), 6.0));
  // рибосомы: по одной крупинке в каждой ячейке воображаемой решётки, только в строме
  vec3 cell = floor(p / 0.30), g = p - (cell + 0.5) * 0.30;
  g -= (vec3(hash(cell), hash(cell + 7.1), hash(cell + 13.7)) - 0.5) * 0.14;
  float rib = max(length(g) - (hash(cell + 3.3) > 0.45 ? 0.016 : -1.0), sdEll(p, RI) + 0.09);
  r = U(r, vec2(max(rib, 0.05 - min(r.x, 0.2)), 7.0));
  // три рибосомы в известном месте — к ним ведёт подпись
  ${RIBO.map(c => `r = U(r, vec2(length(p - ${v3(c)}) - 0.019, 7.0));`).join(' ')}
  r = U(r, vec2(sdEll(p - ${v3(STARCH)}, vec3(0.15, 0.22, 0.15)), 8.0));
  return r;
}
float remap(float m, vec3 p, vec3 n) {
  // внутренняя сторона дальней стенки, видимая сквозь строму, относится к строме
  if (m == 2.0 && cutPlane(p) < -0.04 && dot(n, p) < 0.0) return 3.0;
  return m;
}
vec3 albedo(float m, vec3 p, vec3 n) {
  if (m == 1.0) return vec3(0.62, 0.34, 0.05);
  if (m == 2.0) return vec3(0.95, 0.80, 0.42);
  if (m == 3.0) return vec3(0.16, 0.36, 0.14);
  if (m == 4.0) return mix(vec3(0.02, 0.17, 0.06), vec3(0.07, 0.36, 0.13), smoothstep(0.3, 0.95, abs(n.y)));
  if (m == 5.0) return vec3(0.12, 0.46, 0.20);
  if (m == 6.0) return vec3(0.62, 0.86, 1.0);
  if (m == 7.0) return vec3(0.95, 0.84, 0.62);
  return vec3(0.96, 0.95, 0.90);
}
// строма: полупрозрачный «гель» внутри внутренней мембраны, позади плоскости среза
vec4 haze(vec3 ro, vec3 rd, float tHit) {
  vec3 o = ro / RI, d = rd / RI; float a = dot(d, d), b = dot(o, d), c = dot(o, o) - 1.0, h = b * b - a * c;
  if (h < 0.0) return vec4(0.0);
  h = sqrt(h); float t0 = max((-b - h) / a, 0.0), t1 = min((-b + h) / a, tHit);
  vec3 nrm = vec3(0.0, 0.38, 1.0); float den = dot(rd, nrm), tc = (0.30 - dot(ro, nrm)) / den;
  if (den > 0.0) t1 = min(t1, tc); else t0 = max(t0, tc);
  float len = max(t1 - t0, 0.0);
  return vec4(vec3(0.13, 0.36, 0.13) * (0.9 + 0.25 * rd.y), 1.0 - exp(-len * 0.24));
}`;

