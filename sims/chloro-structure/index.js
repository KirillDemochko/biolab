export function mount(root, api) {
  // пузырьки газов поверх сцены: O₂ поднимается от гран наружу, CO₂ идёт внутрь
  const gases = Array.from({ length: 10 }, (_, i) => ({ kind: i % 2 ? 'co2' : 'o2', k: i / 10, g: GRANA[i % GRANA.length], a: i * 2.4 }));
  function overlay(ctx, { project, dt, w }) {
    for (const p of gases) {
      p.k += dt * 0.16; if (p.k > 1) { p.k = 0; p.g = GRANA[Math.floor(Math.random() * GRANA.length)]; p.a = Math.random() * 6.28; }
      const inside = [p.g[0], p.g[1] + 0.25, p.g[2]], outside = [p.g[0] + Math.cos(p.a) * 0.9, 1.9, p.g[2] + Math.sin(p.a) * 0.5 + 0.3];
      const k = p.kind === 'o2' ? p.k : 1 - p.k, pos = inside.map((v, j) => v + (outside[j] - v) * k), [x, y, z] = project(pos); if (z <= 0) continue;
      const s = mol(p.kind), sc = Math.max(0.5, Math.min(1, w / 760)) * 0.95;
      ctx.globalAlpha = Math.min(1, p.k * 6, (1 - p.k) * 6) * 0.95; ctx.drawImage(s.cv, x - s.w / 2 * sc, y - s.h / 2 * sc, s.w * sc, s.h * sc); ctx.globalAlpha = 1;
    }
  }
  return mountExplorer3D(root, api, {
    label: 'Хлоропласт в разрезе, трёхмерная модель', glsl, bound: 2.3, yaw: 0.36, pitch: 0.52, dist: 5.2, minDist: 2.6, maxDist: 7,
    parts: PARTS, order: ORDER, quest: QUEST, overlay,
    intro: ['Хлоропласт в разрезе', 'Органоид растительной клетки, в котором идёт фотосинтез. Передняя часть оболочки срезана, чтобы было видно внутреннее устройство. Поверни модель, приблизь её кнопкой «+» и нажми на любую часть — здесь появится подробное объяснение.'],
    extra: `<div class="controls"><div class="legend"><span><img src="${molIcon('o2')}" alt="" style="height:12px">кислород выходит из гран наружу</span><span><img src="${molIcon('co2')}" alt="" style="height:12px">углекислый газ идёт в строму</span></div></div>`,
  });
}
